const {chromium}=require('@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},userAgent:'Mozilla/5.0 EolaLocalQualityCheck'});
  const page=await context.newPage(),errors=[],requests=[];
  page.setDefaultNavigationTimeout(90000);
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().includes('/eola-analytics/v1/events'))requests.push(r)});
  await page.goto('http://localhost:8085/?utm_source=booklet&utm_medium=qr&utm_campaign=eola_review',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.eolaAnalyticsLoaded);
  await page.waitForTimeout(1000);
  assert(requests.length>0,'Automatic measurement starts without a popup');
  assert.equal(await page.locator('.eola-analytics-choice').count(),0,'No initial approval popup');
  assert(requests.every(r=>JSON.parse(r.postData()).mode==='automatic'));
  assert(requests.every(r=>!Object.hasOwn(JSON.parse(r.postData()),'consent')),'No fabricated consent flag');
  await page.getByRole('button',{name:'Analytics preferences',exact:true}).click();
  await page.getByRole('button',{name:'Disable analytics',exact:true}).click();
  const disabledCount=requests.length;
  await page.waitForTimeout(1200);assert.equal(requests.length,disabledCount,'No data sent after opt-out');
  await page.reload({waitUntil:'networkidle'});assert.equal(requests.length,disabledCount,'Opt-out survives reload');
  await page.getByRole('button',{name:'Analytics preferences',exact:true}).click();
  const response=page.waitForResponse(r=>r.url().includes('/eola-analytics/v1/events'));
  await page.getByRole('button',{name:'Enable analytics',exact:true}).click();
  assert.equal((await response).status(),200);
  await page.locator('.eola-filter-home a').click();
  await page.locator('.eola-gallery-tile:visible a').first().click();
  await page.keyboard.press('Escape');
  await page.locator('#floor-plans a[href*="floorplan"]').first().evaluate(el=>el.addEventListener('click',e=>e.preventDefault()));
  await page.locator('#floor-plans a[href*="floorplan"]').first().click();
  await page.locator('.elementor-lightbox:visible').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.elementor-lightbox:visible').waitFor({state:'hidden'});
  const pdf=page.locator('a[href*="property-amenities.pdf"]').first();await pdf.evaluate(el=>el.addEventListener('click',e=>e.preventDefault()));await pdf.click();
  const contact=page.locator('a[href^="mailto:"][href*="Private"]').first();await contact.evaluate(el=>el.addEventListener('click',e=>e.preventDefault()));await contact.click();
  await page.locator('#property').scrollIntoViewIfNeeded();
  await page.waitForTimeout(17000);
  const events=requests.flatMap(r=>JSON.parse(r.postData()).events);
  for(const name of ['page_view','gallery_filter','gallery_open','engagement','section_view','floorplan_open','download','contact_click','showing_click']) assert(events.some(e=>e.name===name),name);
  assert(requests.every(r=>JSON.parse(r.postData()).source==='booklet'));
  const payload=JSON.parse(requests[0].postData());
  const duplicate=await context.request.post(requests[0].url(),{data:payload,headers:{Origin:'http://localhost:8085'}});assert.equal(duplicate.status(),200);assert.equal((await duplicate.json()).accepted,0);
  const forged=await context.request.post(requests[0].url(),{data:payload,headers:{Origin:'https://example.org'}});assert.equal(forged.status(),403);
  const invalid=await context.request.post(requests[0].url(),{data:{...payload,events:[{...payload.events[0],name:'arbitrary'}]},headers:{Origin:'http://localhost:8085'}});assert.equal(invalid.status(),400);
  await page.getByRole('button',{name:'Analytics preferences',exact:true}).click();await page.getByRole('button',{name:'Disable analytics',exact:true}).click();
  await page.waitForTimeout(300);const count=requests.length;await page.waitForTimeout(5500);assert.equal(requests.length,count,'Withdrawal stops requests');
  assert.deepEqual(errors,[]);
  const env=Object.fromEntries(fs.readFileSync('.env','utf8').trim().split(/\r?\n/).map(l=>[l.slice(0,l.indexOf('=')),l.slice(l.indexOf('=')+1)]));
  await page.goto('http://localhost:8085/wp-login.php');await page.locator('#user_login').fill(env.EOLA_LOCAL_ADMIN_USER);await page.locator('#user_pass').fill(env.EOLA_LOCAL_ADMIN_PASSWORD);await page.locator('#wp-submit').click();await page.waitForURL('**/wp-admin/**');
  await page.goto('http://localhost:8085/wp-admin/admin.php?page=eola-analytics');
  await page.getByRole('heading',{name:'Eola Analytics',exact:true}).waitFor();
  await page.screenshot({path:'artifacts/screenshots/analytics-dashboard.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  const adminRequests=requests.length;await page.goto('http://localhost:8085/');assert.equal(await page.locator('.eola-analytics-choice').count(),0);assert.equal(requests.length,adminRequests);
  const privateContext=await browser.newContext({extraHTTPHeaders:{DNT:'1'}});
  await privateContext.addInitScript(()=>Object.defineProperty(navigator,'doNotTrack',{get:()=> '1'}));
  const privatePage=await privateContext.newPage();let privateEvents=0;privatePage.on('request',r=>{if(r.url().includes('/eola-analytics/v1/events'))privateEvents++});
  await privatePage.goto('http://localhost:8085/',{waitUntil:'networkidle'});assert.equal(privateEvents,0,'DNT honored');await privateContext.close();
  console.log('PASS: automatic collection without popup or fabricated consent, persistent opt-out, re-enable, real clicks, active engagement, QR attribution, deduplication, forged origins, invalid events, staff exclusion, DNT and dashboard mobile layout.');
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1)});
