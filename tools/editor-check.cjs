const {chromium}=require('@playwright/test');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 const env=Object.fromEntries(fs.readFileSync('.env','utf8').trim().split(/\r?\n/).map(line=>[line.slice(0,line.indexOf('=')),line.slice(line.indexOf('=')+1)]));
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const page=await browser.newPage({viewport:{width:1600,height:1000}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:8085/wp-login.php');
 await page.locator('#user_login').fill(env.EOLA_LOCAL_ADMIN_USER);
 await page.locator('#user_pass').fill(env.EOLA_LOCAL_ADMIN_PASSWORD);
 await page.locator('#wp-submit').click();
 await page.waitForURL('**/wp-admin/**');
 await page.goto('http://localhost:8085/wp-admin/post.php?post=5&action=elementor',{waitUntil:'domcontentloaded',timeout:90000});
 const frame=page.frameLocator('#elementor-preview-iframe');
 console.log('Editor opened; waiting for native document rendering.');
 await frame.locator('h1').waitFor({timeout:240000}).catch(async e=>{console.log('Editor frame did not render:',page.frames().map(f=>f.url()));await browser.close();throw e;});
 await page.locator('#elementor-loading').waitFor({state:'hidden',timeout:90000});
 await frame.locator('h1').click();
 const title=page.locator('[data-setting="title"]');
 await title.waitFor({timeout:15000}).catch(async e=>{await page.screenshot({path:'artifacts/screenshots/editor-failure.png'});console.log((await page.locator('body').innerText()).slice(0,5000));throw e;});
 const original=await title.inputValue();
 console.log('Editing native heading:',original);
 await title.fill('Unmistakably<br>editable.');
 await title.dispatchEvent('input');
 await title.dispatchEvent('change');
 await title.press('End');
 await title.press('Space');
 await title.press('Backspace');
 await title.press('Tab');
 await frame.locator('h1').filter({hasText:'editable.'}).waitFor().catch(async e=>{await page.screenshot({path:'artifacts/screenshots/editor-failure.png'});console.log('Heading:',await frame.locator('h1').innerText());console.log('Control:',await title.inputValue());throw e;});
 const save=page.getByRole('button',{name:'Publish',exact:true});
 await save.click();
 await page.waitForFunction(()=>!elementor.saver.isEditorChanged(),null,{timeout:30000});
 const front=await browser.newPage();
 await front.goto('http://localhost:8085/',{waitUntil:'networkidle'});
 assert.match(await front.locator('h1').innerText(),/editable/);
 await title.fill(original);
 await title.press('Tab');
 await frame.locator('h1').filter({hasText:'special.'}).waitFor();
 await save.click();
 await page.waitForFunction(()=>!elementor.saver.isEditorChanged(),null,{timeout:30000});
 await front.reload({waitUntil:'networkidle'});
 assert.match(await front.locator('h1').innerText(),/special/);
 await front.close();
 await page.screenshot({path:'artifacts/screenshots/elementor-editor.png'});
 console.log('Native Elementor title edited, published, verified on frontend and restored.');
 assert.deepEqual(errors,[]);
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
