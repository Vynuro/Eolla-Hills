const {chromium}=require('@playwright/test');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:8085/',{waitUntil:'networkidle'});
 const hero=page.locator('.eola-immersive-hero');
 const exterior=await hero.evaluate(el=>getComputedStyle(el).backgroundImage);
 await page.locator('.eola-scene-interior a').click();
 assert.equal(await page.locator('.eola-scene-interior a').getAttribute('aria-pressed'),'true');
 assert.notEqual(await hero.evaluate(el=>getComputedStyle(el).backgroundImage),exterior);
 await page.locator('.eola-scene-land a').focus();
 await page.keyboard.press('Space');
 assert.equal(await page.locator('.eola-scene-land a').getAttribute('aria-pressed'),'true');
 await page.locator('.eola-scene-exterior a').click();
 assert.equal(await hero.evaluate(el=>getComputedStyle(el).backgroundImage),exterior);
 await page.locator('#gallery').scrollIntoViewIfNeeded();
 for(const [key,count] of [['home',7],['grounds',4],['spaces',4],['all',15]]){
   await page.locator(`.eola-filter-${key} a`).click();
   assert.equal(await page.locator('.eola-gallery-tile:visible').count(),count);
   assert.equal(await page.locator(`.eola-filter-${key} a`).getAttribute('aria-pressed'),'true');
 }
 await page.locator('.eola-gallery-tile a').first().click();
 await page.locator('.elementor-lightbox').waitFor({state:'visible'});
 await page.screenshot({path:'artifacts/screenshots/gallery-lightbox.png'});
 await page.keyboard.press('Escape');
 await page.locator('.elementor-lightbox').waitFor({state:'hidden'});
 const carousel=page.locator('.eola-property-carousel');
 await carousel.scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>[...document.querySelectorAll('.eola-property-carousel img')].every(img=>img.complete&&img.naturalWidth>=1200));
 const quality=await carousel.locator('img').evaluateAll(imgs=>imgs.map(img=>({source:img.naturalWidth,display:img.getBoundingClientRect().width})));
 assert.ok(quality.every(img=>img.source>=img.display),'Carousel must not upscale small thumbnails.');
 const before=await carousel.locator('.swiper-slide-active img').getAttribute('src');
 await carousel.locator('.elementor-swiper-button-next').click();
 await page.waitForTimeout(800);
 const after=await carousel.locator('.swiper-slide-active img').getAttribute('src');
 assert.notEqual(before,after);
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForTimeout(100);
 assert.equal(await page.evaluate(()=>document.getAnimations().filter(x=>x.playState==='running').length),0);
 await page.locator('#property').scrollIntoViewIfNeeded();
 await page.screenshot({path:'artifacts/screenshots/property-section.png'});
 await page.locator('#gallery').scrollIntoViewIfNeeded();
 await page.screenshot({path:'artifacts/screenshots/gallery-section.png'});
 await page.locator('#film').screenshot({path:'artifacts/screenshots/carousel-quality.png'});
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('Hero photo switching/keyboard controls, filters, native lightbox/keyboard close, carousel navigation, reduced motion and runtime-error checks passed.');
})().catch(e=>{console.error(e);process.exit(1)});
